let toastTimer = null;
/** toast("Saved", {action: {label, run}}) */
export function toast(message, { action = null, ms = 4200 } = {}) {
  const el = $("#toast");
  el.innerHTML = `<span>${esc(message)}</span>${action ? `<button type="button" class="toast-action">${esc(action.label)}</button>` : ""}`;
  el.hidden = false;
  el.classList.remove("show");
  void el.offsetWidth;
  el.classList.add("show");
  if (action) el.querySelector(".toast-action").onclick = () => { action.run(); el.hidden = true; };
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => { el.classList.remove("show"); setTimeout(() => (el.hidden = true), 200); }, ms);
}

/** Wraps words whose stem matches one of the terms' stems in <mark>. Input is plain text. */
export function highlight(text, terms) {
  const stems = new Set(terms.flatMap(t => (t.toLowerCase().match(/[a-z][a-z0-9]+/g) || []).map(stem)).filter(s => s.length > 2));
  if (!stems.size) return esc(text);
  return String(text).split(/([A-Za-z][A-Za-z0-9]+)/).map((part, i) =>
    i % 2 && stems.has(stem(part.toLowerCase())) ? `<mark>${esc(part)}</mark>` : esc(part)).join("");
}

export function authors(list, n = 3) {
  if (!list?.length) return "Unknown authors";
  return list.length <= n + 1 ? list.join(", ") : `${list.slice(0, n).join(", ")} +${list.length - n}`;
}

export function date(iso) {
  if (!iso) return "";
  const d = new Date(iso.length === 4 ? `${iso}-07-01` : iso);
  return Number.isNaN(+d) ? iso : d.toLocaleDateString(undefined, { day: "numeric", month: "short", year: "numeric" });
}

export function ago(iso) {
  if (!iso) return "never";
  const h = (Date.now() - Date.parse(iso)) / 3600000;
  if (h < 1) return "just now";
  if (h < 24) return `${Math.floor(h)} h ago`;
  return `${Math.floor(h / 24)} d ago`;
}

